import { chromium } from 'playwright-core';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
const ROOT = '/Users/jinlong/dev/github/qq-speed-3d';
const MIME = { '.html':'text/html;charset=utf-8', '.js':'text/javascript;charset=utf-8', '.css':'text/css;charset=utf-8' };
const server = createServer(async (req,res)=>{ try{ let p=req.url.split('?')[0]; if(p==='/')p='/index.html';
 const f=join(ROOT, normalize(p)); const d=await readFile(f); res.writeHead(200,{'content-type':MIME[extname(f)]||'application/octet-stream'}); res.end(d);}catch(e){res.writeHead(404);res.end('x');}});
await new Promise(r=>server.listen(8127,r));
const b = await chromium.launch({ channel:'chrome', headless:false, args:['--use-angle=metal'] });
const page = await b.newPage({ viewport:{width:1440,height:860} });
await page.goto('http://localhost:8127/index.html');
await page.waitForTimeout(2500);
const fps = () => page.evaluate(()=>new Promise(res=>{let n=0;const t0=performance.now();const f=()=>{n++;if(performance.now()-t0<1800)requestAnimationFrame(f);else res(+(n/((performance.now()-t0)/1000)).toFixed(1));};requestAnimationFrame(f);}));
const out = {};
out.base = await fps();
out.shadowOff = await page.evaluate(()=>{ window.__race.renderer.shadowMap.enabled=false; window.__race.scene.traverse(o=>{if(o.material)o.material.needsUpdate=true;}); return 1;}).then(fps);
await page.evaluate(()=>{ window.__race.renderer.shadowMap.enabled=true; window.__race.scene.traverse(o=>{if(o.material)o.material.needsUpdate=true;}); });
out.dpr1 = await page.evaluate(()=>{ window.__race.renderer.setPixelRatio(1); return 1;}).then(fps);
await page.evaluate(()=>{ window.__race.renderer.setPixelRatio(Math.min(devicePixelRatio,1.7)); });
out.noTrack = await page.evaluate(()=>{ window.__race.scene.getObjectByName('track').visible=false; return 1;}).then(fps);
await page.evaluate(()=>{ window.__race.scene.getObjectByName('track').visible=true; });
out.noSky = await page.evaluate(()=>{ window.__race.scene.children[0].visible=false; return 1;}).then(fps);
await page.evaluate(()=>{ window.__race.scene.children[0].visible=true; });
out.noPost = await page.evaluate(()=>{ window.__race.renderer.toneMapping=0; return 1;}).then(fps);
const ri = await page.evaluate(()=>{const r=window.__race.renderer; return {calls:r.info.render.calls, tris:r.info.render.triangles, tex:r.info.memory.textures, geo:r.info.memory.geometries};});
console.log(JSON.stringify({out, ri}, null, 1));
await b.close(); server.close();
