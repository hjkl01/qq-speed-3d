import { chromium } from 'playwright-core';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
const ROOT = '/Users/jinlong/dev/github/qq-speed-3d';
const MIME = { '.html':'text/html;charset=utf-8', '.js':'text/javascript;charset=utf-8', '.css':'text/css;charset=utf-8' };
const server = createServer(async (req,res)=>{ try{ let p=req.url.split('?')[0]; if(p==='/')p='/index.html';
 const f=join(ROOT, normalize(p)); const d=await readFile(f); res.writeHead(200,{'content-type':MIME[extname(f)]||'application/octet-stream'}); res.end(d);}catch(e){res.writeHead(404);res.end('x');}});
await new Promise(r=>server.listen(8125,r));
const mode = process.argv[2] || 'gpu';
const b = await chromium.launch({ channel:'chrome', headless: false, args: mode==='gpu' ? ['--use-angle=metal'] : ['--use-gl=angle','--enable-unsafe-swiftshader'] });
const page = await b.newPage({ viewport:{width:1440,height:860} });
const errs=[]; page.on('pageerror',e=>errs.push(e.message));
await page.goto('http://localhost:8125/index.html');
await page.waitForTimeout(2000);
const fps = await page.evaluate(()=>new Promise(res=>{let n=0;const t0=performance.now();const f=()=>{n++;if(performance.now()-t0<3000)requestAnimationFrame(f);else res(+(n/((performance.now()-t0)/1000)).toFixed(1));};requestAnimationFrame(f);}));
const info = await page.evaluate(()=>{const gl=document.getElementById('scene').getContext('webgl2'); const d=gl.getExtension('WEBGL_debug_renderer_info'); return { r: d? gl.getParameter(d.UNMASKED_RENDERER_WEBGL):'?', tris: window.__race.scene.children.length };});
console.log(JSON.stringify({fps, info, errs}));
await b.close(); server.close();
