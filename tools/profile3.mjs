import { chromium } from 'playwright-core';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
const ROOT = '/Users/jinlong/dev/github/qq-speed-3d';
const MIME = { '.html':'text/html;charset=utf-8', '.js':'text/javascript;charset=utf-8', '.css':'text/css;charset=utf-8' };
const server = createServer(async (req,res)=>{ try{ let p=req.url.split('?')[0]; if(p==='/')p='/index.html';
 const f=join(ROOT, normalize(p)); const d=await readFile(f); res.writeHead(200,{'content-type':MIME[extname(f)]||'application/octet-stream'}); res.end(d);}catch(e){res.writeHead(404);res.end('x');}});
await new Promise(r=>server.listen(8128,r));
const b = await chromium.launch({ channel:'chrome', headless:false, args:['--use-angle=metal'] });
const page = await b.newPage({ viewport:{width:1440,height:860} });
await page.goto('http://localhost:8128/index.html');
await page.waitForTimeout(1500);
await page.click('#btnStart');
await page.waitForTimeout(6000);
const p = await page.evaluate(()=>({perf: window.__perf, w: innerWidth, h: innerHeight, dpr: devicePixelRatio, canvas:[document.getElementById('scene').width, document.getElementById('scene').height]}));
const fps = await page.evaluate(()=>new Promise(res=>{let n=0;const t0=performance.now();const f=()=>{n++;if(performance.now()-t0<2000)requestAnimationFrame(f);else res(+(n/((performance.now()-t0)/1000)).toFixed(1));};requestAnimationFrame(f);}));
console.log(JSON.stringify({...p, fps}, null, 1));
await b.close(); server.close();
